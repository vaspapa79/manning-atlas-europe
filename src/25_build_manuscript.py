INLINE = re.compile(r"\*\*(.+?)\*\*|\*(.+?)\*|`(.+?)`|_\{([^{}]+?)\}|\^\{([^{}]+?)\}")
FIGCAP = re.compile(r"^\*\*Figure (S?\d+)\.?\*\*")
CAPTION_LINE = re.compile(r"^\*\*(Figure|Table) (S?\d+|A\.\d+)\.")


def latex_to_text(s):
    """Light LaTeX -> readable Unicode for equations rendered as plain text."""
    s = re.sub(r"\\tag\{([^}]*)\}", r"    (\1)", s).replace("\\qquad", "    ").replace("\\quad", "   ")
    s = s.replace("\\tfrac", "\\frac").replace("\\dfrac", "\\frac")
    s = re.sub(r"\\(?:text|mathrm|bar|overline|mathbf|mathbb)\{([^{}]*)\}", r"\1", s)
    for _ in range(4):
        s = re.sub(r"\^\{([^{}]*)\}", r"^(\1)", s)
        s = re.sub(r"_\{([^{}]*)\}", r"_(\1)", s)
    for _ in range(4):
        s = re.sub(r"\\frac\{([^{}]*)\}\{([^{}]*)\}", r"(\1)/(\2)", s)
    s = re.sub(r"\\sqrt\{([^{}]*)\}", r"sqrt(\1)", s)
    s = re.sub(r"\\big[lr]?|\\Big[lr]?", "", s)
    # escaped braces are a literal set notation and must survive the strip below
    s = s.replace("\\{", "\ue010").replace("\\}", "\ue011")
    reps = {"\\sum": "Σ", "\\times": "×", "\\partial": "∂", "\\Delta": "Δ", "\\rho": "ρ",
            "\\sim": "~", "\\in": "∈", "\\dots": "…", "\\max": "max", "\\min": "min",
            "\\mathrm": "", "\\,": " ", "\\;": " ", "\\!": "", "\\left": "", "\\right": "",
            "\\cdot": "·", "{": "", "}": "", "$": ""}
    for k, v in reps.items():
        s = s.replace(k, v)
    s = s.replace("\ue010", "{").replace("\ue011", "}")
    return s.strip()


def add_runs(p, text):
    text = text.replace(r"\*", "\ue000").replace("$", "")
    pos = 0
    for m in INLINE.finditer(text):
        if m.start() > pos:
            p.add_run(text[pos:m.start()].replace("\ue000", "*"))
        b, i, c, sub, sup = (m.group(1), m.group(2), m.group(3),
                             m.group(4), m.group(5))
        if b is not None:
            r = p.add_run(b.replace("\ue000", "*")); r.bold = True
        elif i is not None:
            r = p.add_run(i.replace("\ue000", "*")); r.italic = True
        elif c is not None:
            r = p.add_run(c.replace("\ue000", "*")); r.font.name = "Consolas"
        elif sub is not None:
            # _{x} becomes a real subscript run, never a literal underscore
            r = p.add_run(sub.replace("\ue000", "*")); r.font.subscript = True
        else:
            r = p.add_run(sup.replace("\ue000", "*")); r.font.superscript = True
        pos = m.end()
    if pos < len(text):
        p.add_run(text[pos:].replace("\ue000", "*"))


# --------------------------------------------------------------------------
# The journal asks for tables without vertical rules or cell shading, so the
# tables are drawn in the "booktabs" manner: a rule above and below the table
# and one under the header row, nothing else.
# --------------------------------------------------------------------------
def _no_rules(table, n_rows):
    """Strip every rule and every cell shading: the tables carry no lines at all,
    only the header row set in bold."""
    for row in table.rows:
        for cell in row.cells:
            tcPr = cell._tc.get_or_add_tcPr()
            for tag in ("w:tcBorders", "w:shd"):
                for el in tcPr.findall(qn(tag)):
                    tcPr.remove(el)
            borders = OxmlElement("w:tcBorders")
            for edge in ("top", "bottom", "left", "right", "insideH", "insideV"):
                el = OxmlElement("w:" + edge)
                el.set(qn("w:val"), "nil")
                borders.append(el)
            tcPr.append(borders)
    _ = n_rows


def flush_table(doc, rows):
    rows = [r for r in rows if not re.match(r"^\s*:?-{2,}", r[0].strip())]
    if not rows:
        return
    ncol = max(len(r) for r in rows)
    t = doc.add_table(rows=0, cols=ncol)
    t.style = "Table Grid"
    for ri, cells in enumerate(rows):
        wr = t.add_row().cells
        for ci in range(ncol):
            txt = cells[ci].strip() if ci < len(cells) else ""
            wr[ci].text = ""
            p = wr[ci].paragraphs[0]
            add_runs(p, txt)
            for run in p.runs:
                run.font.size = Pt(8)
                if ri == 0:
                    run.bold = True
            if ci > 0:
                p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    _no_rules(t, len(rows))
    doc.add_paragraph()


def assemble():
    chunks = []
    for name in PARTS:
        path = os.path.join(PARTS_DIR, name)
        if not os.path.exists(path):
            raise SystemExit(f"missing manuscript part: {path}")
        chunks.append(open(path, encoding="utf-8").read().rstrip() + "\n")
    text, supp = relocate("\n".join(chunks))
    with open(MD, "w", encoding="utf-8") as f:
        f.write(text)
    with open(SUPP_MD, "w", encoding="utf-8") as f:
        f.write(supp)
    print(f"assembled {len(PARTS)} parts -> {MD} ({len(text):,} chars)")
    print(f"supplementary -> {SUPP_MD} ({len(supp):,} chars)")
    return text, supp


# --------------------------------------------------------------------------
# Figures and tables belong immediately after the paragraph that first cites
# them, never collected at the end. We therefore lift every caption block out
# of wherever it was written and re-insert it at its first mention.
# --------------------------------------------------------------------------
CAP_RE = re.compile(r"^\*\*(Figure|Table) (S?\d+|A\.\d+)\.\*\*")


def _pull_blocks(lines):
    """Remove every figure/table caption block and return {(kind, tag): block}."""
    blocks, kept, i = {}, [], 0
    while i < len(lines):
        m = CAP_RE.match(lines[i].strip())
        if not m:
            kept.append(lines[i])
            i += 1
            continue
        kind, tag = m.group(1), m.group(2)
        if tag.startswith("A"):          # appendix tables stay in the Appendix
            kept.append(lines[i])
            i += 1
            continue
        block = [lines[i]]
        i += 1
        # a table caption is followed by a blank line then the pipe table
        while i < len(lines) and not lines[i].strip():
            block.append(lines[i])
            i += 1
        if i < len(lines) and lines[i].strip().startswith("|"):
            while i < len(lines) and lines[i].strip().startswith("|"):
                block.append(lines[i])
                i += 1
        elif kind == "Table":
            pass
        else:
            block = block[:1]           # a figure caption is the caption alone
            while kept and not kept[-1].strip():
                break
        blocks[(kind, tag)] = [l for l in block if l.strip()]
        while i < len(lines) and not lines[i].strip():
            i += 1
    return kept, blocks


def relocate(text):
    lines = text.split("\n")
    kept, blocks = _pull_blocks(lines)
    # drop the now-empty "Figure captions" heading, keeping any prose under it
    kept = [l for l in kept if l.strip() != "## Figure captions"]

    placed, out = set(), []
    def _next_is_equation(idx):
        """True when the next thing after kept[idx] is a display equation."""
        for n in range(idx + 1, len(kept)):
            t = kept[n].strip()
            if not t:
                continue
            return t.startswith("$$")
        return False

    pending = []

    def _flush():
        for key in sorted(set(pending), key=lambda k: (k[0] != "Table",
                                                       k[1][0].isalpha(),
                                                       int(re.sub(r"\D", "", k[1]) or 0))):
            placed.add(key)
            out.append("")
            out.extend(blocks[key])
            out.append("")
        del pending[:]

    for i, line in enumerate(kept):
        out.append(line)
        s = line.strip()
        if s.startswith("$$"):
            # the equation has been written; anything held back goes after it,
            # so a figure never separates a sentence from the equation it
            # introduces
            _flush()
            continue
        if not s or s.startswith("#") or s.startswith("|"):
            continue
        for kind in ("Table", "Figure"):
            for tag in re.findall(rf"{kind} (A\.\d+|S?\d+)(?!\d)", s):
                key = (kind, tag)
                if tag.startswith(chr(83)):   # S-series lives in the supplement
                    continue
                if key in blocks and key not in placed and key not in pending:
                    pending.append(key)
        if pending and not _next_is_equation(i):
            _flush()
    _flush()
    supp_keys = [k for k in blocks if k[1].startswith("S")]
    orphans = [k for k in blocks if k not in placed and k not in supp_keys]
    if orphans:
        out.append("")
        for key in orphans:
            out.extend(blocks[key])
            out.append("")
        print("  NOTE: never cited, left at end:",
              ", ".join(f"{k[0]} {k[1]}" for k in orphans))
    print(f"  relocated {len(placed)} figure/table blocks to their first mention")

    # the supplementary items go to their own document, figures then tables
    supp = [SUPP_HEADER]
    for kind in ("Figure", "Table"):
        keys = sorted([k for k in supp_keys if k[0] == kind],
                      key=lambda k: int(k[1][1:]))
        if not keys:
            continue
        supp.append("## Supplementary %ss" % kind.lower())
        supp.append("")
        for key in keys:
            supp.extend(blocks[key])
            supp.append("")
    print(f"  moved {len(supp_keys)} blocks to the supplementary document")
    return "\n".join(out), "\n".join(supp)


def _blacken(doc):
    """Every run in body, headings and tables set to black, and every body run
    set to Calibri 11 explicitly rather than inheriting it from Normal."""
    BLACK = RGBColor(0, 0, 0)
    for para in doc.paragraphs:
        body = para.style.name in ("Normal", "List Bullet")
        for run in para.runs:
            run.font.color.rgb = BLACK
            if body and run.font.name is None:
                run.font.name = "Calibri"
                run.font.size = Pt(11)
    for t in doc.tables:
        for row in t.rows:
            for cell in row.cells:
                for para in cell.paragraphs:
                    for run in para.runs:
                        run.font.color.rgb = BLACK


def render(text, out_path=None):
    out_path = out_path or OUT
    doc = Document()
    normal = doc.styles["Normal"]
    normal.font.name = "Calibri"
    normal.font.size = Pt(11)
    normal.font.color.rgb = RGBColor(0, 0, 0)

    # the built-in Title style is 26 pt and carries a bottom rule
    title = doc.styles["Title"]
    title.font.name = "Calibri"
    title.font.size = Pt(16)
    for bdr in title.element.findall(qn("w:pPr") + "/" + qn("w:pBdr")):
        bdr.getparent().remove(bdr)

    table_buf = []
    missing = []
    math_count = [0]
    fallback = [0]
    for ln in text.splitlines():
        if ln.strip().startswith("|"):
            table_buf.append([c.strip() for c in ln.strip().strip("|").split("|")])
            continue
        if table_buf:
            flush_table(doc, table_buf)
            table_buf = []

        s = ln.strip()
        if not s or s == "---":
            continue
        if s.startswith("$$"):
            body, tag = omml.split_tag(s.strip("$").strip())
            el = omml.to_omml(s)
            p = doc.add_paragraph()
            if el is not None:
                # centred equation, number right-aligned at the margin
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                p._p.append(el)
                if tag:
                    p.paragraph_format.tab_stops.add_tab_stop(
                        Inches(6.4), WD_TAB_ALIGNMENT.RIGHT)
                    p.add_run("\t(%s)" % tag)
                math_count[0] += 1
            else:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                r = p.add_run(latex_to_text(s))
                r.italic = True
                r.font.name = "Cambria Math"
                fallback[0] += 1
            continue
        if s.startswith("> "):
            # a plain indented paragraph: the Intense Quote style carries a
            # coloured rule, and the document is to have neither
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Inches(0.4)
            p.paragraph_format.right_indent = Inches(0.4)
            add_runs(p, s[2:])
            for r in p.runs:
                r.bold = True
            continue
        if s.startswith("- "):
            p = doc.add_paragraph(style="List Bullet")
            add_runs(p, s[2:])
            continue
        if s.startswith("#### "):
            doc.add_heading(s[5:].strip(), level=3)
            continue
        if s.startswith("### "):
            doc.add_heading(s[4:].strip(), level=2)
            continue
        if s.startswith("## "):
            doc.add_heading(s[3:].strip(), level=1)
            continue
        if s.startswith("# "):
            h = doc.add_heading(s[2:].strip(), level=0)
            h.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
            for r in h.runs:
                r.font.name = "Calibri"
                r.font.size = Pt(16)
            continue

        m = FIGCAP.match(s)
        if m and m.group(1) in FIG_FILES:
            fp, win = FIG_FILES[m.group(1)]
            if os.path.exists(fp):
                pim = doc.add_paragraph()
                pim.alignment = WD_ALIGN_PARAGRAPH.CENTER
                pim.add_run().add_picture(fp, width=Inches(win))
            else:
                missing.append((m.group(1), fp))
        p = doc.add_paragraph()
        add_runs(p, s)
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY

    if table_buf:
        flush_table(doc, table_buf)
    _blacken(doc)
    doc.save(out_path)
    print("wrote", out_path)
    if math_count[0] or fallback[0]:
        print("   equations: %d as native Word maths, %d as plain text%s"
              % (math_count[0], fallback[0],
                 "" if not fallback[0] else " (" + omml.why_unavailable() + ")"))
    if missing:
        print("MISSING FIGURE FILES:")
        for tag, fp in missing:
            print(f"  Figure {tag}: {fp}")


if __name__ == "__main__":
    main_text, supp_text = assemble()
    render(main_text, OUT)
    render(supp_text, SUPP_OUT)
    render(open(HL_MD, encoding="utf-8").read(), HL_OUT)
